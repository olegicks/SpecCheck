"""Report exports: Markdown, CSV, JSON and Excel."""

from __future__ import annotations

import csv
import io
import json
from enum import StrEnum

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from app.checks.models import CheckRun, RequirementResult


class ExportFormat(StrEnum):
    MD = "md"
    CSV = "csv"
    JSON = "json"
    XLSX = "xlsx"


MEDIA_TYPES = {
    ExportFormat.MD: "text/markdown; charset=utf-8",
    ExportFormat.CSV: "text/csv; charset=utf-8",
    ExportFormat.JSON: "application/json",
    ExportFormat.XLSX: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
}

COLUMNS = (
    "Requirement", "Title", "Priority", "Criterion", "Status", "Agent status", "Found value",
    "Page", "Quote", "Confidence", "Quote verified", "Reason", "Override comment",
)  # fmt: skip

_FILLS = {"PASS": "DCFCE7", "FAIL": "FEE2E2", "UNCLEAR": "FEF3C7"}
# Cells starting with these characters are interpreted as formulas by spreadsheet apps.
_FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r")


def _row(r: RequirementResult) -> list[str | float | int | None]:
    f = r.finding
    return [
        r.requirement.id,
        r.requirement.title,
        r.requirement.priority.value,
        r.requirement.describe(),
        r.status.value,
        r.agent_status.value,
        r.found_display,
        f.page if f else None,
        f.quote if f else None,
        round(f.confidence, 2) if f else None,
        ("yes" if r.verification.verified else "no") if r.verification else None,
        r.reason,
        r.override.comment if r.override else None,
    ]


def _safe_cell(value: object) -> object:
    """Prevent CSV/Excel formula injection from datasheet-derived text."""
    if isinstance(value, str) and value.startswith(_FORMULA_PREFIXES):
        if value.lstrip("+-").replace(".", "", 1).isdigit():
            return value
        return "'" + value
    return value


def _md_escape(value: object) -> str:
    return "" if value is None else str(value).replace("|", "\\|").replace("\n", " ")


def to_markdown(run: CheckRun) -> str:
    s = run.summary
    lines = [
        "# SpecCheck report",
        "",
        f"- **Datasheet:** {run.datasheet.get('filename')} "
        f"({run.datasheet.get('page_count')} pages)",
        f"- **Check ID:** `{run.id}`",
        f"- **Mode / model:** {run.mode} / {run.model}",
        f"- **Created:** {run.created_at:%Y-%m-%d %H:%M UTC}",
        f"- **Result:** {s.passed} PASS · {s.failed} FAIL · {s.unclear} UNCLEAR"
        + (f" ({s.overridden} overridden by reviewer)" if s.overridden else ""),
        "",
        "| ID | Requirement | Criterion | Status | Found | Page | Confidence |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in run.results:
        f = r.finding
        status = r.status.value + (" ✎" if r.override else "")
        lines.append(
            "| "
            + " | ".join(
                _md_escape(v)
                for v in (
                    r.requirement.id,
                    r.requirement.title,
                    r.requirement.describe(),
                    f"**{status}**",
                    r.found_display or "—",
                    f.page if f and f.page else "—",
                    f"{f.confidence:.2f}" if f else "—",
                )
            )
            + " |"
        )
    lines += ["", "## Details", ""]
    for r in run.results:
        f = r.finding
        lines.append(f"### {r.requirement.id} — {r.requirement.title}: {r.status.value}")
        lines.append("")
        lines.append(f"- Criterion: {r.requirement.describe()}")
        lines.append(f"- Decision: {r.reason}")
        if f and f.quote:
            lines.append(f"- Evidence (page {f.page}): > {_md_escape(f.quote)}")
        if r.verification:
            v = r.verification
            lines.append(
                f"- Quote verification: {'verified' if v.verified else 'FAILED'} ({v.method})"
            )
        if f and f.notes:
            lines.append(f"- Agent notes: {_md_escape(f.notes)}")
        if r.override:
            lines.append(
                f"- **Reviewer override:** {r.agent_status.value} → {r.override.status.value}: "
                f"{_md_escape(r.override.comment)}"
            )
        lines.append("")
    lines.append(
        "_Generated by SpecCheck. Statuses are decided by a deterministic rule engine "
        "from LLM-extracted, quote-verified values._"
    )
    return "\n".join(lines) + "\n"


def to_csv(run: CheckRun) -> str:
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(COLUMNS)
    for r in run.results:
        writer.writerow([_safe_cell(v) for v in _row(r)])
    return out.getvalue()


def to_json(run: CheckRun) -> str:
    return json.dumps(run.model_dump(mode="json"), indent=2, ensure_ascii=False)


def to_xlsx(run: CheckRun) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "Results"
    ws.append(list(COLUMNS))
    for cell in ws[1]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor="1E3A5F")
    for r in run.results:
        ws.append([_safe_cell(v) for v in _row(r)])
        status_cell = ws.cell(row=ws.max_row, column=COLUMNS.index("Status") + 1)
        status_cell.fill = PatternFill("solid", fgColor=_FILLS[r.status.value])
        status_cell.font = Font(bold=True)
    widths = (12, 34, 9, 26, 10, 12, 18, 6, 60, 11, 13, 50, 40)
    for i, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = width
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")
    ws.freeze_panes = "A2"

    meta = wb.create_sheet("Run")
    s = run.summary
    for key, value in (
        ("Check ID", run.id),
        ("Datasheet", run.datasheet.get("filename")),
        ("Mode", run.mode),
        ("Model", run.model),
        ("Created (UTC)", run.created_at.strftime("%Y-%m-%d %H:%M")),
        ("PASS", s.passed),
        ("FAIL", s.failed),
        ("UNCLEAR", s.unclear),
        ("Overridden", s.overridden),
    ):
        meta.append([key, _safe_cell(value)])
    meta.column_dimensions["A"].width = 16
    meta.column_dimensions["B"].width = 40

    buffer = io.BytesIO()
    wb.save(buffer)
    return buffer.getvalue()


def export(run: CheckRun, fmt: ExportFormat) -> bytes:
    match fmt:
        case ExportFormat.MD:
            return to_markdown(run).encode()
        case ExportFormat.CSV:
            return ("\ufeff" + to_csv(run)).encode()  # BOM so Excel opens UTF-8 correctly
        case ExportFormat.JSON:
            return to_json(run).encode()
        case ExportFormat.XLSX:
            return to_xlsx(run)
